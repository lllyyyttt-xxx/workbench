/* 活动名归一
 *
 * 时间记录里的活动名是人随口写的：「刷手机」「玩手机」「刷抖音」其实是一件事，
 * 要是各算一条，看板画出来全是碎片。这里把常见说法归到统一的类别和活动上。
 *
 * 两件事：
 *   1. guessCat(text)     猜这件事属于哪个类别，只返回课表里已有的那十个类别；
 *   2. canonical(text)    把活动名归成一个标准说法，用于聚合统计。
 *
 * 类别表跟时间管理模块保持一致，改那边记得同步这边。
 */
window.WorkbenchNormalize = (function () {
  'use strict';

  var CATS = ['上课', '作业', '自学', '社团', '通勤', '运动', '社交', '刷手机', '娱乐', '休息'];

  /* 顺序有讲究：越具体的越靠前，先命中先用。
   * 比如「吃饭刷视频」要算刷手机，不能因为有个「吃饭」就算休息。 */
  var RULES = [
    { cat: '上课', words: ['上课', '听课', '在课上', '课堂', '实验课', '上大课'] },
    { cat: '作业', words: ['作业', '写代码', '敲代码', '实验报告', '课程设计', '大作业', '改bug', '交作业'] },
    { cat: '通勤', words: ['通勤', '路上', '坐车', '公交', '地铁', '骑车', '走路去', '回宿舍路上'] },
    { cat: '刷手机', words: ['刷手机', '玩手机', '刷视频', '刷抖音', '刷b站', '刷B站', '刷微博', '刷小红书', '短视频', '看手机', '躺着刷'] },
    { cat: '运动', words: ['运动', '跑步', '健身', '篮球', '游泳', '打球', '散步', '锻炼', '体测', '拉练'] },
    { cat: '社交', words: ['社交', '聊天', '和朋友', '聚会', '宿舍聊', '打电话', '见朋友', '一起吃饭'] },
    { cat: '社团', words: ['社团', '例会', '开会', '学生会', '部门', '活动策划'] },
    { cat: '娱乐', words: ['娱乐', '游戏', '打游戏', '开黑', '看剧', '追剧', '电影', '听歌', '唱歌', '桌游'] },
    { cat: '自学', words: ['自学', '复习', '预习', '背单词', '背词', '刷题', '看书', '阅读', '学习', '四级', '六级', '写博客'] },
    { cat: '休息', words: ['休息', '睡觉', '午休', '午睡', '躺', '发呆', '吃饭', '洗漱', '洗澡', '赖床', '小憩', '打盹'] }
  ];

  /* 活动名归一：左边是标准说法，右边是各种写法的关键词 */
  var ACTS = [
    ['刷手机', ['刷手机', '玩手机', '刷视频', '刷抖音', '刷b站', '刷B站', '刷微博', '刷小红书', '短视频']],
    ['睡觉', ['睡觉', '午睡', '午休', '小睡', '补觉', '赖床', '打盹']],
    ['吃饭', ['吃饭', '干饭', '早饭', '午饭', '晚饭', '夜宵', '食堂']],
    ['打游戏', ['打游戏', '游戏', '开黑', '手游', '端游']],
    ['看剧', ['看剧', '追剧', '看番', '看电影', '刷剧']],
    ['跑步', ['跑步', '慢跑', '夜跑', '晨跑']],
    ['健身', ['健身', '撸铁', '练背', '练腿', '力量']],
    ['背单词', ['背单词', '背词', '单词', '记单词']],
    ['写作业', ['写作业', '做作业', '写代码', '敲代码', '实验报告', '大作业', '课程设计']],
    ['自习', ['自习', '复习', '预习', '学习', '看书', '刷题']],
    ['洗澡', ['洗澡', '洗漱', '冲凉']],
    ['通勤', ['通勤', '路上', '坐车', '地铁', '公交', '骑车']],
    ['发呆', ['发呆', '放空', '刷手机发呆']]
  ];

  /* 这个词出现了，就基本能定类别 */
  function guessCat(text, fallback) {
    var s = String(text || '');
    for (var i = 0; i < RULES.length; i++) {
      var words = RULES[i].words;
      for (var k = 0; k < words.length; k++) {
        if (s.indexOf(words[k]) >= 0) return RULES[i].cat;
      }
    }
    return fallback || '';
  }

  function canonical(text) {
    var s = String(text || '');
    for (var i = 0; i < ACTS.length; i++) {
      for (var k = 0; k < ACTS[i][1].length; k++) {
        if (s.indexOf(ACTS[i][1][k]) >= 0) return ACTS[i][0];
      }
    }
    return s.trim().slice(0, 12) || '其他';
  }

  function isCat(name) {
    return CATS.indexOf(String(name || '')) >= 0;
  }

  /* 类别不认识就猜一个，猜不出来算休息，别让记录落空 */
  function fixCat(name, text) {
    var c = String(name || '').trim();
    if (isCat(c)) return c;
    var g = guessCat(text, '');
    return g || (c ? '休息' : '休息');
  }

  return {
    CATS: CATS,
    guessCat: guessCat,
    canonical: canonical,
    isCat: isCat,
    fixCat: fixCat
  };
})();
